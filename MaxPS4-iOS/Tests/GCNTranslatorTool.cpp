// Stage 1 of the translator test: translate every fixture, check refusals,
// and write the generated functions (C++/MSL subset) to the given file.
#include "../Native/GCNShaderTranslator.hpp"
#include "GCNTranslatorFixtures.hpp"
#include <cstdio>
#include <fstream>
#include <iostream>

int main(int argc, char** argv) {
  if (argc != 2) { std::cerr << "usage: GCNTranslatorTool OUTPUT.inc\n"; return 2; }
  std::ofstream out(argv[1]);
  out << "// Generated by GCNTranslatorTool from GCNTranslatorFixtures.hpp. Do not edit.\n";
  unsigned translated = 0, refused = 0;
  for (const auto& f : gcnfix::all()) {
    const auto r = maxps4::gpu::GCNShaderTranslator::translate(f.code, f.vgprs);
    if (f.translatable) {
      if (!r.ok) { std::cerr << f.name << ": unexpected refusal: " << r.error << '\n'; return 1; }
      out << maxps4::gpu::GCNShaderTranslator::function(f.name, r) << '\n';
      std::cout << f.name << ": " << r.instructions << " instructions translated"
                << (r.needsScalarPrepass ? ", scalar prepass" : "") << (r.usesImages ? ", images" : "")
                << (r.usesInterpolation ? ", interpolation" : "") << '\n';
      ++translated;
    } else {
      if (r.ok) { std::cerr << f.name << ": translated although it must be refused\n"; return 1; }
      if (r.error.find(f.refusal) == std::string::npos) { std::cerr << f.name << ": wrong refusal: " << r.error << '\n'; return 1; }
      std::cout << f.name << ": refused (" << r.error << ")\n";
      ++refused;
    }
  }
  std::cout << "PASS translator stage 1: " << translated << " translated, " << refused << " refused with their reason\n";
}
