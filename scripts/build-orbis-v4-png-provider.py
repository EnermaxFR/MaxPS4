#!/usr/bin/env python3
"""Generate the bounded, relocation-free x86 guest PNG header provider.
The checked-in output is consumed on iOS; clang is needed only to regenerate.
"""
from pathlib import Path
import argparse, hashlib, os, re, subprocess, tempfile
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check",action="store_true")
args=parser.parse_args()
root=Path(__file__).resolve().parents[1]
source=root/'MaxPS4-iOS/Native/GuestProviders/png_header.c'
output=root/'MaxPS4-iOS/Native/GuestProviders/png_header.inc'
with tempfile.TemporaryDirectory(prefix='maxps4-png-') as d:
    obj=Path(d)/'png.o'; binary=Path(d)/'png.bin'
    subprocess.run([os.environ.get('CC','clang'),'-target','x86_64-unknown-linux-gnu','-Oz','-ffreestanding','-fno-builtin','-fno-stack-protector','-fno-unwind-tables','-fno-asynchronous-unwind-tables','-fno-jump-tables','-mno-sse','-mno-mmx','-mno-red-zone','-c',str(source),'-o',str(obj)],check=True)
    reloc=subprocess.check_output(['objdump','-r',str(obj)],text=True)
    if 'RELOCATION RECORDS' in reloc:raise RuntimeError('guest code contains relocations')
    assembly=subprocess.check_output(['objdump','-d',str(obj)],text=True)
    if not re.search(r'lock orb\s+\$0x0,',assembly):
        raise RuntimeError('required volatile byte write-probe is missing from guest code')
    symbols=subprocess.check_output(['nm','-S','--defined-only',str(obj)],text=True)
    undefined=subprocess.check_output(['nm','-u',str(obj)],text=True)
    if undefined.strip():raise RuntimeError('guest code has undefined symbols')
    subprocess.run(['objcopy','-O','binary','--only-section=.text',str(obj),str(binary)],check=True)
    data=binary.read_bytes()
    if not 0<len(data)<=1024:raise RuntimeError('guest code exceeds PRX code budget')
    lines=['// Generated by scripts/build-orbis-v4-png-provider.py; do not edit.', '// source SHA256 '+hashlib.sha256(source.read_bytes()).hexdigest(), '// code SHA256 '+hashlib.sha256(data).hexdigest(), 'static constexpr uint8_t png_code[]={']
    lines += ['    '+','.join(f'0x{x:02x}' for x in data[i:i+16])+',' for i in range(0,len(data),16)]
    lines+=['};']
    for line in symbols.splitlines():
        address,size,kind,name=line.split()
        if name in ('png_parse','png_create','png_decode','png_query'):
            if kind!='T':raise RuntimeError('export is not text')
            start=int(address,16);length=int(size,16)
            if not length or start+length>len(data):raise RuntimeError('invalid export')
            lines.append(f'static constexpr size_t {name}_offset={start}, {name}_size={length};')
    generated='\n'.join(lines)+'\n'
    if args.check:
        if output.read_text()!=generated:raise RuntimeError('checked-in guest code differs; regenerate and review')
    else:output.write_text(generated)
